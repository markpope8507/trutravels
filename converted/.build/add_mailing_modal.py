"""
Put the mailing-list popup on every static page, and point the footer at it.

    python3 converted/.build/add_mailing_modal.py

WHY A POPUP. The list asks for email, first and last name and nationality.
Four fields in the footer strip would crowd it, so the strip keeps one
email-shaped field and clicking it (or Sign Up) opens the full form.

A POST-BUILD STEP, like add_cookie_banner.py: the footer is on every page and
the pages come from a dozen builders, so one pass over the directory is the
only place this lives once.

ONE DEFINITION. The markup and script are sliced out of
components/mailing-list-modal.html between its COPY FROM/TO markers. Edit the
component, re-run this.

THE FOOTER. The strip's <form data-mailform> becomes a row of two buttons
carrying data-ml-open. explore.html is rewritten too — shell.py slices FOOTER
out of it, so new pages pick the opener up from there.

RE-RUNNABLE. The injected block sits between START/END comments and is
replaced wholesale on each run, so an edit to the component reaches every page.
"""

import os
import re

from shell import BASE

COMPONENT = os.path.join(BASE, "components", "mailing-list-modal.html")
MARK_A = "<!-- COPY FROM HERE                                                     -->"
MARK_B = "<!-- COPY TO HERE                                                       -->"

START = "<!-- mailing-list-modal:start (generated by .build/add_mailing_modal.py) -->"
END = "<!-- mailing-list-modal:end -->"
EXISTING = re.compile(r"\n?" + re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.S)

OLD_FORM = re.compile(
    r'<form class="footer__form" data-mailform>\s*'
    r'<input type="email" required placeholder="your@email.com" aria-label="Email address" />\s*'
    r'<button type="submit">Sign Up</button>\s*'
    r'</form>'
)
NEW_FORM = (
    '<div class="footer__form" data-ml-strip>\n'
    '            <button type="button" class="footer__form-field" data-ml-open aria-haspopup="dialog">your@email.com</button>\n'
    '            <button type="button" data-ml-open aria-haspopup="dialog">Sign Up</button>\n'
    '          </div>'
)


def block():
    """The popup markup and script, as the component defines them."""
    src = open(COMPONENT, encoding="utf-8").read()
    a = src.index(MARK_A) + len(MARK_A)
    b = src.index(MARK_B)
    out = src[a:b].strip("\n")
    # The component sits one level down; the pages are all at the site root.
    out = out.replace('href="../', 'href="')
    if "data-ml-modal" not in out or "<script>" not in out:
        raise SystemExit("add_mailing_modal: sliced block is missing the modal or the script")
    return "\n" + START + "\n" + out + "\n" + END + "\n"


def main():
    blk = block()
    added = refreshed = rewired = 0
    for fn in sorted(os.listdir(BASE)):
        if not fn.endswith(".html"):
            continue
        p = os.path.join(BASE, fn)
        html = open(p, encoding="utf-8").read()
        before = html

        html, n = OLD_FORM.subn(NEW_FORM, html)
        rewired += n

        if "data-ml-open" not in html:
            continue  # no footer strip, nothing to open the popup

        had = START in html
        html = EXISTING.sub("", html)
        # The LAST </body>: the cookie banner's comment mentions "</body>" in
        # its prose, and inserting there would land inside that comment.
        cut = html.rfind("</body>")
        if cut == -1:
            print("  %-46s no </body>, left alone" % fn)
            continue
        html = html[:cut] + blk + html[cut:]
        if not had:
            added += 1
        elif html != before:
            refreshed += 1

        if html != before:
            open(p, "w", encoding="utf-8").write(html)

    print("  footer rewired on %d pages" % rewired)
    print("  popup added to %d pages, refreshed on %d" % (added, refreshed))
    if not (added or refreshed or rewired):
        print("  (nothing to do)")


if __name__ == "__main__":
    main()
